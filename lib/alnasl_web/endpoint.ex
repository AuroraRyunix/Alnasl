defmodule AlnaslWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :alnasl

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_alnasl_key",
    signing_salt: "vbWM74o7",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Arkab bridges (`AlnaslWeb.BridgeSocket`): a program, not a browser, so
  # no origin to check and no session; the key is in the first frame. Two
  # minutes of silence ends it (the bridge pings every 25 seconds).
  socket "/bridge/link", AlnaslWeb.BridgeSocket,
    websocket: [path: "", check_origin: false, timeout: 120_000],
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  # The favicon is the mark (`AlnaslWeb.Logo`), made from priv/logo/mark.svg,
  # so it is answered here and not read from priv/static.
  plug :favicon

  plug Plug.Static,
    at: "/",
    from: :alnasl,
    gzip: not code_reloading?,
    only: AlnaslWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :alnasl
  end

  # The launcher's Details panel - this machine, a secret, no proxy header, or
  # a 404. Before the request logger, so a panel left open does not log its
  # own polling into the log it shows. See the plug.
  plug AlnaslWeb.Plugs.LauncherStats

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug AlnaslWeb.Router

  @doc false
  def favicon(%Plug.Conn{request_path: "/favicon.svg"} = conn, _opts) do
    conn
    |> Plug.Conn.put_resp_content_type("image/svg+xml")
    |> Plug.Conn.put_resp_header("cache-control", "public, max-age=3600")
    |> Plug.Conn.send_resp(200, AlnaslWeb.Logo.favicon())
    |> Plug.Conn.halt()
  end

  def favicon(conn, _opts), do: conn
end
