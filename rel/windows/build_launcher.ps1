<#
.SYNOPSIS
    Builds Alnasl.exe, the launcher that starts the release on Windows.

.DESCRIPTION
    launcher.c is the program and its header comment is the reasoning; this
    only compiles it. `mix release` runs it as a release step (mix.exs,
    windows_launcher/1) and puts the result at the root of the release. Run
    it by hand when you are working on the launcher itself.

.NOTES
    Zig, because `zig cc` brings its own C library and Windows headers (no
    Visual Studio to install), cross-compiles from anywhere, and makes an
    executable of about 100 KB with no runtime behind it. Only `zig cc` and
    `zig rc` are used - clang's and rc.exe's interfaces - so the Zig version
    matters little; the release workflow pins one all the same.

    The version comes from mix.exs unless given: the executable's
    Properties page cannot then say something else than the release it
    starts.
#>

[CmdletBinding()]
param(
    [string]$OutputPath = "$PSScriptRoot\Alnasl.exe",
    [string]$Version,
    [string]$Zig = 'zig'
)

$ErrorActionPreference = 'Stop'

if (-not (Get-Command $Zig -ErrorAction SilentlyContinue)) {
    throw "zig not found. Install it (scoop install zig) or pass -Zig <path>."
}

if (-not $Version) {
    $match = Select-String -Path (Join-Path $PSScriptRoot '..\..\mix.exs') `
        -Pattern 'version:\s*"([0-9]+\.[0-9]+\.[0-9]+)"' | Select-Object -First 1
    if (-not $match) { throw "Could not read the version from mix.exs; pass -Version." }
    $Version = $match.Matches[0].Groups[1].Value
}

$parts = $Version.Split('.')
if ($parts.Count -ne 3) { throw "Version must be MAJOR.MINOR.PATCH, got '$Version'." }

# Generated, not committed: see .gitignore beside this file.
$objDir = Join-Path $PSScriptRoot 'obj'
New-Item -ItemType Directory -Force -Path $objDir | Out-Null

@"
/* Generated by build_launcher.ps1 - do not edit, do not commit. */
#define ALNASL_VER_MAJOR $($parts[0])
#define ALNASL_VER_MINOR $($parts[1])
#define ALNASL_VER_PATCH $($parts[2])
#define ALNASL_VER_STRING "$Version"
"@ | Out-File -FilePath (Join-Path $objDir 'launcher_version.h') -Encoding ascii

$res = Join-Path $objDir 'launcher.res'

Push-Location $PSScriptRoot
try {
    # Options before the input file: `zig rc` stops reading options at the
    # first argument that is not one.
    & $Zig rc /nologo /i $objDir /fo $res launcher.rc
    if ($LASTEXITCODE -ne 0) { throw "zig rc failed with exit code $LASTEXITCODE" }

    # /subsystem:windows is what makes it a program without a console
    # window. The release workflow reads the flag back out of the file.
    & $Zig cc `
        -target x86_64-windows-gnu `
        -Os -s `
        -Wall -Wextra `
        "-Wl,/subsystem:windows" `
        launcher.c $res `
        -o $OutputPath `
        -luser32 -lgdi32 -lshell32 -ladvapi32 -lcomctl32 -lws2_32
    if ($LASTEXITCODE -ne 0) { throw "zig cc failed with exit code $LASTEXITCODE" }
}
finally {
    Pop-Location
}

Get-Item $OutputPath |
    Select-Object Name, @{n = 'KB'; e = { [math]::Round($_.Length / 1KB, 1) } }, FullName |
    Format-Table -AutoSize
